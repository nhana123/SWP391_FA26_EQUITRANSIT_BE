CREATE TABLE dbo.RevisionQuarantineAssessment (
    AssessmentID BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    RevisionID BIGINT NOT NULL,
    Applicability VARCHAR(20) NOT NULL
        CHECK (Applicability IN ('PENDING','NOT_REQUIRED','REQUIRED')),
    RequiredDays INT NULL CHECK (RequiredDays IS NULL OR RequiredDays > 0),
    SpecialistID BIGINT NOT NULL,
    AssessedAt DATETIME2(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ValidUntil DATETIME2(0) NULL,
    SourceReference NVARCHAR(1000) NULL,
    SupersededAt DATETIME2(0) NULL,
    RuleID BIGINT NULL,
    AssessmentNotes NVARCHAR(2000) NULL,
    CONSTRAINT PK_RevisionQuarantineAssessment PRIMARY KEY (AssessmentID)
);

CREATE VIEW dbo.QuarantineAssessment AS
    SELECT AssessmentID, RevisionID, Applicability, RequiredDays, RuleID,
        AssessmentNotes, SpecialistID AS AssessedBy, AssessedAt,
        ValidUntil, SourceReference, SupersededAt
    FROM dbo.RevisionQuarantineAssessment
    WHERE SupersededAt IS NULL;

CREATE TABLE dbo.OrderRevision (
    RevisionID BIGINT PRIMARY KEY,
    OrderID BIGINT,
    OriginCountryCode VARCHAR(2),
    DestinationCountryCode VARCHAR(2),
    PreferredDepartureAt DATETIME2(0)
);
